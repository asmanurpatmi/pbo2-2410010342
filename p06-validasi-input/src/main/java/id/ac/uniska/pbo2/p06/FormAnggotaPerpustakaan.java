    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed

        java.util.List<javax.swing.JComponent> salah = new java.util.ArrayList<>();

        if (!periksaNpm()) {
            salah.add(npmField);
        }

        if (!periksaNama()) {
            salah.add(namaField);
        }

        if (!periksaEmail()) {
            salah.add(emailField);
        }

        if (!periksaHp()) {
            salah.add(hpField);
        }
        
        if (jenisAnggotaGroup.getSelection() == null) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Silakan pilih jenis anggota.",
                "Validasi Data",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );

            mahasiswaRadioButton.requestFocusInWindow();
            return;
        }
        
        jumlahError = salah.size();

        if (jumlahError > 0) {
            statusLabel.setForeground(java.awt.Color.RED);
            statusLabel.setText(
                "Terdapat " + jumlahError
                + " kesalahan. Silakan periksa data berwarna merah."
            );

            salah.get(0).requestFocusInWindow();
            return;
        }

        statusLabel.setForeground(new java.awt.Color(0, 128, 0));
        statusLabel.setText("Data berhasil divalidasi!");

        String jenisAnggota = "";

        if (mahasiswaRadioButton.isSelected()) {
            jenisAnggota = "Mahasiswa";
        } else if (dosenRadioButton.isSelected()) {
            jenisAnggota = "Dosen";
        } else if (umumRadioButton.isSelected()) {
            jenisAnggota = "Umum";
        }

        String ringkasan = "RINGKASAN DATA ANGGOTA\n\n"
        + "NPM: " + npmField.getText() + "\n"
        + "Nama: " + namaField.getText() + "\n"
        + "Program Studi: " + prodiComboBox.getSelectedItem() + "\n"
        + "Jenis Anggota: " + jenisAnggota + "\n"
        + "Email: " + emailField.getText() + "\n"
        + "Nomor HP: " + hpField.getText() + "\n"
        + "Alamat: " + jTextArea1.getText();

        javax.swing.JOptionPane.showMessageDialog(
            this,
            ringkasan,
            "Ringkasan Pendaftaran",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );
    }//GEN-LAST:event_daftarButtonActionPerformed

    private void batalButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_batalButtonActionPerformed
        boolean adaIsi =
        !npmField.getText().trim().isEmpty()
        || !namaField.getText().trim().isEmpty()
        || !emailField.getText().trim().isEmpty()
        || !hpField.getText().trim().isEmpty()
        || !jTextArea1.getText().trim().isEmpty()
        || jenisAnggotaGroup.getSelection() != null
        || jCheckBox1.isSelected();

        if (adaIsi) {
            int jawab = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Apakah Anda yakin ingin menghapus semua data?",
                "Konfirmasi Hapus",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.QUESTION_MESSAGE
            );

            if (jawab != javax.swing.JOptionPane.YES_OPTION) {
                return;
            }
        }

        npmField.setText("");
        namaField.setText("");
        emailField.setText("");
        hpField.setText("");
        jTextArea1.setText("");

        prodiComboBox.setSelectedIndex(0);
        jenisAnggotaGroup.clearSelection();
        jCheckBox1.setSelected(false);

        npmErrorLabel.setText(" ");
        namaErrorLabel.setText(" ");
        emailErrorLabel.setText(" ");
        hpErrorLabel.setText(" ");

        npmField.putClientProperty("JComponent.outline", null);
        namaField.putClientProperty("JComponent.outline", null);
        emailField.putClientProperty("JComponent.outline", null);
        hpField.putClientProperty("JComponent.outline", null);

        jumlahError = 0;

        npmField.requestFocusInWindow();
    }//GEN-LAST:event_batalButtonActionPerformed

