    private boolean tandai(
            JComponent isian,
            JLabel pesan,
            String kesalahan) {

        boolean valid = (kesalahan == null);

        // Mengatur garis tepi kolom
        isian.putClientProperty(
            "JComponent.outline",
            valid ? null : "error"
        );

        // Mengatur tulisan pesan kesalahan
        pesan.setText(valid ? " " : kesalahan);

        if (valid) {
            pesan.setForeground(java.awt.Color.BLACK);
        } else {
        pesan.setForeground(java.awt.Color.RED);
        }

        return valid;
    }
    
    private boolean periksaNpm() {
        return tandai(
            npmField,
            npmErrorLabel,
            Validator.npm(npmField.getText())
        );
    }

    private boolean periksaNama() {
        return tandai(
            namaField,
            namaErrorLabel,
            Validator.nama(namaField.getText())
        );
    }

    private boolean periksaEmail() {
        return tandai(
            emailField,
            emailErrorLabel,
            Validator.email(emailField.getText())
        );
    }

    private boolean periksaHp() {
        return tandai(
            hpField,
            hpErrorLabel,
            Validator.nomorHp(hpField.getText())
        );
    }

